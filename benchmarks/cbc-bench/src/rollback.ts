import {
  evaluatePerformanceRollback,
  type PerformanceHealthWindow,
  type PerformanceRollbackDecision,
} from "@cbc/config-schema";

export type RolloutProfile = "api-standard" | "api-fast" | "account";

export interface PerformanceHealthArtifact {
  readonly schemaVersion: "1.0";
  readonly capturedAt: string;
  readonly profile: RolloutProfile;
  readonly commit: string;
  readonly capabilityDigest: string;
  readonly cohortDigest: string;
  readonly window: PerformanceHealthWindow;
}

export interface PerformanceRollbackArtifact {
  readonly schemaVersion: "1.0";
  readonly health: PerformanceHealthArtifact;
  readonly decision: PerformanceRollbackDecision;
  readonly toml: string;
}

export function parsePerformanceHealthArtifact(value: unknown): PerformanceHealthArtifact {
  if (!isRecord(value) || value.schemaVersion !== "1.0") {
    throw new Error("performance health artifact must be a schemaVersion 1.0 object");
  }
  if (typeof value.capturedAt !== "string" || Number.isNaN(Date.parse(value.capturedAt))) {
    throw new Error("performance health artifact needs an ISO capturedAt timestamp");
  }
  if (value.profile !== "api-standard" && value.profile !== "api-fast" && value.profile !== "account") {
    throw new Error("performance health artifact profile must be api-standard, api-fast, or account");
  }
  if (typeof value.commit !== "string" || value.commit.trim().length === 0) {
    throw new Error("performance health artifact needs an exact commit");
  }
  if (!validDigest(value.capabilityDigest)) {
    throw new Error("performance health artifact capabilityDigest must be SHA-256 evidence");
  }
  if (!validDigest(value.cohortDigest)) {
    throw new Error("performance health artifact cohortDigest must be SHA-256 evidence");
  }
  if (!isRecord(value.window)) {
    throw new Error("performance health artifact needs a window object");
  }
  const window = parseHealthWindow(value.window);
  // The evaluator is the threshold source of truth and performs the final range checks.
  evaluatePerformanceRollback(window);
  return {
    schemaVersion: "1.0",
    capturedAt: value.capturedAt,
    profile: value.profile,
    commit: value.commit,
    capabilityDigest: value.capabilityDigest as string,
    cohortDigest: value.cohortDigest as string,
    window,
  };
}

export function evaluatePerformanceHealthArtifact(
  value: unknown,
): PerformanceRollbackArtifact {
  const health = parsePerformanceHealthArtifact(value);
  const decision = evaluatePerformanceRollback(health.window);
  return {
    schemaVersion: "1.0",
    health,
    decision,
    toml: renderRollbackToml(decision.overrides),
  };
}

/** Render dotted config overrides as a deterministic TOML snippet. */
export function renderRollbackToml(overrides: Readonly<Record<string, unknown>>): string {
  const entries = Object.entries(overrides).sort(([left], [right]) => left.localeCompare(right));
  if (entries.length === 0) return "# No rollback overrides are required.\n";

  const tables = new Map<string, Array<{ readonly key: string; readonly value: unknown }>>();
  for (const [path, value] of entries) {
    const segments = path.split(".");
    if (segments.length < 2 || segments.some((segment) => segment.length === 0)) {
      throw new Error(`rollback override path '${path}' is not a dotted config key`);
    }
    const key = segments.pop() as string;
    const table = segments.join(".");
    const group = tables.get(table) ?? [];
    group.push({ key, value });
    tables.set(table, group);
  }

  const lines = [
    "# Generated by cbc-bench rollback. Apply at user/global rollout scope.",
  ];
  for (const table of [...tables.keys()].sort()) {
    lines.push("", `[${snakePath(table)}]`);
    for (const entry of tables.get(table) ?? []) {
      lines.push(`${snakeKey(entry.key)} = ${tomlValue(entry.value)}`);
    }
  }
  return `${lines.join("\n")}\n`;
}

function parseHealthWindow(value: Record<string, unknown>): PerformanceHealthWindow {
  return {
    unapprovedSideEffects: numberField(value, "unapprovedSideEffects"),
    staleContextMutations: numberField(value, "staleContextMutations"),
    falseCompletions: numberField(value, "falseCompletions"),
    continuationFallbackRatio: numberField(value, "continuationFallbackRatio"),
    websocketProtocolErrorRatio: numberField(value, "websocketProtocolErrorRatio"),
    p95LatencyRatio: numberField(value, "p95LatencyRatio"),
    qualityCiLowerPoints: numberField(value, "qualityCiLowerPoints"),
    promptDigestMismatches: numberField(value, "promptDigestMismatches"),
  };
}

function numberField(parent: Record<string, unknown>, key: string): number {
  const value = parent[key];
  if (typeof value !== "number" || !Number.isFinite(value)) {
    throw new Error(`performance health window '${key}' must be a finite number`);
  }
  return value;
}

function validDigest(value: unknown): boolean {
  return typeof value === "string" && /^(?:sha256:)?[0-9a-f]{64}$/u.test(value);
}

function snakePath(path: string): string {
  return path.split(".").map(snakeKey).join(".");
}

function snakeKey(value: string): string {
  return value.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`);
}

function tomlValue(value: unknown): string {
  if (typeof value === "boolean") return String(value);
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" && Number.isFinite(value)) return String(value);
  throw new Error(`rollback override value '${String(value)}' is not TOML scalar data`);
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}
