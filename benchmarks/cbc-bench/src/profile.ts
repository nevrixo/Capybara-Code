import type { EvalProfile } from "@cbc/evals";

export type PromptCacheMode = "off" | "roi" | "always";
export type PerformanceVariant = "legacy" | "optimized";
export type BenchmarkServiceTier = "standard" | "fast";

export interface ExecutionProfileOptions {
  readonly performanceVariant?: PerformanceVariant;
  readonly serviceTier?: BenchmarkServiceTier;
}

export interface BenchmarkPerformanceConfig {
  readonly promptCompiler: "v1" | "v2";
  readonly compoundTools: boolean;
  readonly commandClassification: boolean;
  readonly providerParallelTools: boolean;
  readonly reviewPolicy: "always" | "risk";
  readonly orientationMode: "strict" | "progressive";
  readonly providerCompaction: boolean;
  readonly phasePolicy: boolean;
  readonly transport: "http_full" | "websocket";
  readonly serviceTier: BenchmarkServiceTier;
  readonly toolSearch: boolean;
  readonly telemetry: true;
  readonly sampleRate: 1;
}

const PERFORMANCE_VARIANTS: Readonly<
  Record<PerformanceVariant, Omit<BenchmarkPerformanceConfig, "serviceTier">>
> = {
  legacy: {
    promptCompiler: "v1",
    compoundTools: false,
    commandClassification: false,
    providerParallelTools: false,
    reviewPolicy: "always",
    orientationMode: "strict",
    providerCompaction: false,
    phasePolicy: false,
    transport: "http_full",
    toolSearch: false,
    telemetry: true,
    sampleRate: 1,
  },
  optimized: {
    promptCompiler: "v2",
    compoundTools: true,
    commandClassification: true,
    providerParallelTools: true,
    reviewPolicy: "risk",
    orientationMode: "progressive",
    providerCompaction: true,
    phasePolicy: true,
    transport: "websocket",
    toolSearch: false,
    telemetry: true,
    sampleRate: 1,
  },
};

export interface ResolvedExecutionProfile {
  readonly schemaVersion: "1.0";
  readonly requested: EvalProfile;
  readonly applied: EvalProfile;
  readonly performanceVariant: PerformanceVariant;
  readonly mechanisms: {
    readonly autoReview: "cli:--review";
    readonly toolDiscovery: "native:tool.discover";
    readonly subagents: "native:task.*";
    readonly promptCache: "user-config:model.cache.mode";
    readonly performanceVariant: "user-config:performance-feature-set";
  };
  readonly cli: {
    readonly review: "auto" | "off";
  };
  readonly config: {
    readonly modelCacheMode: PromptCacheMode;
    readonly performance: BenchmarkPerformanceConfig;
  };
}

/**
 * Translate every eval axis into product controls that the CBC application consumes.
 *
 * A comparison profile is refused when the application has no corresponding switch.
 * Passing a benchmark-only environment label would make the result look controlled
 * while leaving runtime behaviour unchanged, which is worse than an explicit failure.
 */
export function resolveExecutionProfile(
  profile: EvalProfile,
  options: ExecutionProfileOptions = {},
): ResolvedExecutionProfile {
  const unsupported: string[] = [];
  if (!profile.toolDiscovery) {
    unsupported.push(
      "toolDiscovery=false requires a product switch that pre-activates every tool schema; CBC does not expose one",
    );
  }
  if (!profile.subagents) {
    unsupported.push(
      "subagents=false requires a product switch that removes task.* tools and disables spawning; CBC does not expose one",
    );
  }
  if (unsupported.length > 0) {
    throw new UnsupportedProfileError(profile.id, unsupported);
  }

  const performanceVariant = options.performanceVariant ?? "optimized";
  const performance = {
    ...PERFORMANCE_VARIANTS[performanceVariant],
    serviceTier: options.serviceTier ?? "standard",
  } satisfies BenchmarkPerformanceConfig;

  return {
    schemaVersion: "1.0",
    requested: cloneProfile(profile),
    applied: cloneProfile(profile),
    performanceVariant,
    mechanisms: {
      autoReview: "cli:--review",
      toolDiscovery: "native:tool.discover",
      subagents: "native:task.*",
      promptCache: "user-config:model.cache.mode",
      performanceVariant: "user-config:performance-feature-set",
    },
    cli: { review: profile.autoReview ? "auto" : "off" },
    config: {
      modelCacheMode: cacheMode(profile.promptCache),
      performance,
    },
  };
}

export interface BenchmarkConfigOptions {
  readonly network?: "deny" | "ask" | "allow";
  /** Shell-free verification commands explicitly pre-approved for the isolated fixture. */
  readonly approvalCommands?: readonly string[];
}

export function benchmarkConfigToml(
  profile: ResolvedExecutionProfile,
  options: BenchmarkConfigOptions = {},
): string {
  const performance = profile.config.performance;
  const approvalRules = renderApprovalRules(options.approvalCommands ?? []);
  return [
    "# Generated by cbc-bench. This directory is deleted after the run.",
    "[perf]",
    `telemetry = ${String(performance.telemetry)}`,
    `sample_rate = ${performance.sampleRate}`,
    "",
    "[agent]",
    `prompt_compiler = "${performance.promptCompiler}"`,
    `compound_tools = ${String(performance.compoundTools)}`,
    "",
    "[agent.tool_graph]",
    `command_classification = ${String(performance.commandClassification)}`,
    `provider_parallel_tools = ${String(performance.providerParallelTools)}`,
    "",
    "[agent.verification]",
    `review_policy = "${performance.reviewPolicy}"`,
    "",
    "[model.context]",
    `orientation_mode = "${performance.orientationMode}"`,
    `provider_compaction = ${String(performance.providerCompaction)}`,
    "",
    "[model.router]",
    `phase_policy = ${String(performance.phasePolicy)}`,
    "",
    "[model.cache]",
    `mode = "${profile.config.modelCacheMode}"`,
    "",
    "[provider.openai]",
    `transport = "${performance.transport}"`,
    `service_tier = "${performance.serviceTier}"`,
    `tool_search = ${String(performance.toolSearch)}`,
    "",
    ...(options.network === undefined
      ? []
      : [
          "[permissions]",
          `network = "${options.network}"`,
          "",
          "[sandbox]",
          `network_for_shell = "${options.network}"`,
          "",
        ]),
    ...approvalRules,
  ].join("\n");
}

export interface BenchmarkApprovalCommand {
  readonly program: string;
  readonly argsPrefix: readonly string[];
}

/** Parse a declared verification command without invoking or emulating a shell. */
export function parseBenchmarkApprovalCommand(command: string): BenchmarkApprovalCommand {
  if (/[|&;><]/u.test(command)) {
    throw new Error(`benchmark verification command contains a shell operator: ${command}`);
  }
  const parts: string[] = [];
  let current = "";
  let quote: string | undefined;
  for (const character of command.trim()) {
    if (quote !== undefined) {
      if (character === quote) quote = undefined;
      else current += character;
      continue;
    }
    if (character === '"' || character === "'") {
      quote = character;
      continue;
    }
    if (/\s/u.test(character)) {
      if (current.length > 0) {
        parts.push(current);
        current = "";
      }
      continue;
    }
    current += character;
  }
  if (quote !== undefined) throw new Error(`unterminated quote in benchmark command: ${command}`);
  if (current.length > 0) parts.push(current);
  const [program = "", ...argsPrefix] = parts;
  if (program.length === 0 || argsPrefix.length === 0) {
    throw new Error(`benchmark verification command must include a program and subcommand: ${command}`);
  }
  return { program, argsPrefix };
}

function renderApprovalRules(commands: readonly string[]): string[] {
  const unique = new Map<string, BenchmarkApprovalCommand>();
  for (const command of commands) {
    const parsed = parseBenchmarkApprovalCommand(command);
    unique.set(`${parsed.program}\u0000${parsed.argsPrefix.join("\u0000")}`, parsed);
  }
  return [...unique.values()].flatMap((command) => [
    "[[permissions.rules]]",
    `tool = "process.run"`,
    `decision = "allow"`,
    `risk = "R1"`,
    `program = ${JSON.stringify(command.program)}`,
    `args_prefix = [${command.argsPrefix.map((argument) => JSON.stringify(argument)).join(", ")}]`,
    "",
  ]);
}

export class UnsupportedProfileError extends Error {
  readonly profileId: string;
  readonly reasons: readonly string[];

  constructor(profileId: string, reasons: readonly string[]) {
    super(`profile '${profileId}' cannot be applied faithfully:\n- ${reasons.join("\n- ")}`);
    this.name = "UnsupportedProfileError";
    this.profileId = profileId;
    this.reasons = [...reasons];
  }
}

function cacheMode(mode: EvalProfile["promptCache"]): PromptCacheMode {
  if (mode === "off") return "off";
  if (mode === "aggressive") return "always";
  return "roi";
}

function cloneProfile(profile: EvalProfile): EvalProfile {
  return {
    id: profile.id,
    description: profile.description,
    model: profile.model,
    reasoningMode: profile.reasoningMode,
    reasoningEffort: profile.reasoningEffort,
    autoReview: profile.autoReview,
    toolDiscovery: profile.toolDiscovery,
    subagents: profile.subagents,
    promptCache: profile.promptCache,
  };
}
